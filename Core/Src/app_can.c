/*----------------------------------------------------------------------------*/
#define CMD_BASE_ID  0x300
/*----------------------------------------------------------------------------*/


/*----------------------------------------------------------------------------*/
typedef enum {
  CMD_PING        = 0x01,
  CMD_SET_RATE    = 0x02,  // arg0 = rate
  CMD_LED         = 0x03,  // arg0=0/1
  CMD_CALIBRATE   = 0x04
} NodeCmd;
/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/

/*----------------------------------------------------------------------------*/
BaseType_t CanCmd_SendToNode(uint8_t node, uint8_t cmd,
                            uint8_t a0, uint8_t a1, uint8_t a2,
                            uint32_t param32)
{
  uint8_t d[8] = {
    cmd, a0, a1, a2,
    (uint8_t)(param32 & 0xFF),
    (uint8_t)((param32 >> 8) & 0xFF),
    (uint8_t)((param32 >> 16) & 0xFF),
    (uint8_t)((param32 >> 24) & 0xFF),
  };

  return CanRtosTx_SendStd_Async((uint16_t)(CMD_BASE_ID + node), d, 8);
}

